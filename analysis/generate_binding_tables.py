"""Generate src/platform/binding_tables.rs from the installed Dishonored2.exe.

Tables (null-name terminated):
  0x141ac0d80 actions       {i32 id; char* name; char* label}  stride 0x18 (FUN_140038b60)
  0x141ac0250 key icons     {i32 key; char* name}              stride 0x10 (FUN_140039e50)
  0x141abf180 key names     {i32 key; char* name; char* loc}   stride 0x18 (FUN_14003b4f0)
  0x141ac1200 binding sets  {i32 id; char* name}               stride 0x10 (FUN_14003b460)
Usage: python -I analysis/generate_binding_tables.py <Dishonored2.exe> <out.rs>
"""
import json
import struct
import sys

import pefile

exe, out = sys.argv[1], sys.argv[2]
pe = pefile.PE(exe, fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
data = open(exe, 'rb').read()


def offset(va):
    for s in pe.sections:
        start = base + s.VirtualAddress
        if start <= va < start + max(s.Misc_VirtualSize, s.SizeOfRawData):
            return s.PointerToRawData + va - start
    raise ValueError(hex(va))


def read(va, n):
    o = offset(va)
    return data[o:o + n]


def cstr(va):
    o = offset(va)
    return data[o:data.index(b'\0', o)].decode('latin1')


def table(va, stride, strings):
    """The rows a lookup visits: it stops at the first null name pointer.
    The icon table has no terminator of its own, so its walk continues into
    the following data; those rows are kept only when a key code (0..0xff)
    can match them, and must then point at strings."""
    rows = []
    while True:
        key = struct.unpack('<i', read(va, 4))[0]
        ptrs = struct.unpack('<%dQ' % strings, read(va + 8, 8 * strings))
        if ptrs[0] == 0:
            return rows
        if 0 <= key <= 0xff or stride == 0x18:
            rows.append((key,) + tuple(cstr(p) if p else '' for p in ptrs))
        va += stride


def rs(s):
    return json.dumps(s)


actions = table(0x141ac0d80, 0x18, 2)
icons = table(0x141ac0250, 0x10, 1)
names = table(0x141abf180, 0x18, 2)
sets = table(0x141ac1200, 0x10, 1)

with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('//! Generated by analysis/generate_binding_tables.py from Dishonored2.exe.\n')
    f.write('//! Do not edit by hand.\n\n')
    f.write('/// `{id, name, label}` at 0x141ac0d80 (`FUN_140038b60`).\n')
    f.write('pub const ACTIONS: &[(i32, &str, &str)] = &[\n')
    for k, n, l in actions:
        f.write('    (%d, %s, %s),\n' % (k, rs(n), rs(l)))
    f.write('];\n\n/// `{key, icon name}` at 0x141ac0250 (`FUN_140039e50`).\n')
    f.write('pub const KEY_ICONS: &[(u32, &str)] = &[\n')
    for k, n in icons:
        f.write('    (%#x, %s),\n' % (k, rs(n)))
    f.write('];\n\n/// `{key, name, string key}` at 0x141abf180 (`FUN_14003b4f0`, `FUN_140039d60`).\n')
    f.write('pub const KEY_NAMES: &[(u32, &str, &str)] = &[\n')
    for k, n, l in names:
        f.write('    (%#x, %s, %s),\n' % (k, rs(n), rs(l)))
    f.write('];\n\n/// `{id, name}` at 0x141ac1200 (`FUN_14003b460`).\n')
    f.write('pub const BINDING_SETS: &[(i32, &str)] = &[\n')
    for k, n in sets:
        f.write('    (%d, %s),\n' % (k, rs(n)))
    f.write('];\n')
print(len(actions), len(icons), len(names), len(sets))
