"""Generate src/flash/native_table.rs from the Iggy native-class inventory.

Input: artifacts/ui-pause/iggy-natives.json, extracted from Iggy's class
registration (FUN_14104cc40, globals FUN_141061410) in Dishonored2.exe.
Usage: python -I analysis/generate_native_table.py <inventory.json> <out.rs>
"""
import json
import math
import sys

src, out = sys.argv[1], sys.argv[2]
classes = json.load(open(src, encoding='utf8'))


def rs(s):
    return json.dumps(s if s is not None else '')


def ns(m):
    n = m.get('namespace')
    if n in (None, 'public'):
        return 'Ns::Public'
    if n == 'http://adobe.com/AS3/2006/builtin':
        return 'Ns::As3'
    return 'Ns::Uri(%s)' % rs(n)


def imp(m):
    b = m.get('behaviour', '') or ''
    fn = m.get('fn')
    if b.startswith('throw IllegalOperationError'):
        return 'Imp::ThrowIllegalOperation'
    if b.startswith('throw TypeError'):
        return 'Imp::ThrowType'
    if b.startswith('noop'):
        return 'Imp::Noop'
    if b.startswith('return_constant false'):
        return 'Imp::Return(Const::Bool(false))'
    if b.startswith('return_constant true'):
        return 'Imp::Return(Const::Bool(true))'
    if b.startswith('return_constant null'):
        return 'Imp::Return(Const::Null)'
    if b.startswith('return_constant undefined'):
        return 'Imp::Return(Const::Undefined)'
    if b.startswith('return_constant int'):
        return 'Imp::Return(Const::Int(%d))' % int(b.split()[2])
    if b.startswith('return_this'):
        return 'Imp::ReturnThis'
    if b.startswith('tail_jump'):
        return 'Imp::Native(%s)' % b.split()[1]
    if b.startswith('interface declaration'):
        return 'Imp::Interface'
    if fn in (None, ''):
        return 'Imp::None'
    return 'Imp::Native(%s)' % fn


def const(m):
    t, v = m.get('value_type'), m.get('value')
    if t == 'int':
        return 'Const::Int(%d)' % v
    if t in ('double', 'number'):
        f = float(v)
        if math.isnan(f):
            return 'Const::Number(f64::NAN)'
        if math.isinf(f):
            return 'Const::Number(f64::%s)' % ('INFINITY' if f > 0 else 'NEG_INFINITY')
        return 'Const::Number(%r)' % f
    if t == 'string':
        return 'Const::Str(%s)' % rs(v)
    if t in ('bool', 'boolean'):
        return 'Const::Bool(%s)' % ('true' if v else 'false')
    if t == 'null':
        return 'Const::Null'
    if t == 'undefined' or t is None:
        return 'Const::Undefined'
    if t == 'nan':
        return 'Const::Number(f64::NAN)'
    if t == 'infinity':
        return 'Const::Number(f64::INFINITY)'
    raise SystemExit('unknown constant type %r in %r' % (t, m))


KIND = {
    'method': 'Kind::Method', 'getter': 'Kind::Getter', 'setter': 'Kind::Setter',
    'static_method': 'Kind::StaticMethod', 'static_getter': 'Kind::StaticGetter',
    'static_setter': 'Kind::StaticSetter', 'static_const': 'Kind::StaticConst',
    'field_get': 'Kind::FieldGet', 'field_set': 'Kind::FieldSet', 'var': 'Kind::Var',
    'static_var': 'Kind::StaticVar', 'proto_method': 'Kind::ProtoMethod',
    'global_function': 'Kind::GlobalFunction', 'global_const': 'Kind::GlobalConst',
}

lines = [
    '//! Iggy\'s native AS3 classes, as registered by `FUN_14104cc40` (classes)',
    '//! and `FUN_141061410` (globals) in Dishonored2.exe.',
    '//!',
    '//! Generated by `analysis/generate_native_table.py`; do not edit by hand.',
    'use super::native_decl::*;',
    '',
    'pub static CLASSES: &[ClassDecl] = &[',
]
for c in classes:
    members = []
    for m in c['members']:
        k = m.get('kind')
        if k == 'reserved_slot':
            continue
        if k not in KIND:
            raise SystemExit('unknown member kind %r' % k)
        value = 'Const::Undefined'
        if k in ('static_const', 'global_const', 'var', 'static_var'):
            value = const(m)
        cond = m.get('condition')
        cond = 'Cond::SwfVersionAbove9' if cond and cond.startswith('swf_version') else ('Cond::Unknown' if cond else 'Cond::Always')
        members.append(
            '        Member { kind: %s, name: %s, package: %s, ty: %s, ns: %s, imp: %s, value: %s, offset: %d, cond: %s },'
            % (KIND[k], rs(m.get('name')), rs(m.get('package')), rs(m.get('type')), ns(m), imp(m), value, m.get('offset') or 0, cond))
    ctor = c.get('ctor_behaviour') or ''
    if ctor.startswith('throw IllegalOperationError'):
        ctor_imp = 'Imp::ThrowIllegalOperation'
    elif ctor.startswith('throw TypeError'):
        ctor_imp = 'Imp::ThrowType'
    elif ctor.startswith('noop'):
        ctor_imp = 'Imp::Noop'
    elif ctor.startswith('tail_jump'):
        ctor_imp = 'Imp::Native(%s)' % ctor.split()[1]
    elif c.get('ctor'):
        ctor_imp = 'Imp::Native(%s)' % c['ctor']
    else:
        ctor_imp = 'Imp::None'
    cond = c.get('condition')
    lines.append('    ClassDecl {')
    lines.append('        package: %s, name: %s, base: %s,' % (rs(c.get('package')), rs(c['name']), rs(c.get('base'))))
    lines.append('        ctor: %s, interface: %s, interfaces: &[%s], cond: %s,' % (
        ctor_imp, 'true' if c.get('is_interface') else 'false',
        ', '.join(rs(i) for i in c.get('interfaces') or []),
        'Cond::Unknown' if cond else 'Cond::Always'))
    lines.append('        members: &[')
    lines.extend(['    ' + m for m in members])
    lines.append('        ],')
    lines.append('    },')
lines.append('];')
open(out, 'w', encoding='utf8', newline='\n').write('\n'.join(lines) + '\n')
print('classes', len(classes), 'members', sum(len(c['members']) for c in classes))
