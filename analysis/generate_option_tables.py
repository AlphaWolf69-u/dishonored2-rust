"""Generate src/gameplay/options/tables.rs from Dishonored2.exe's reflection enums.

Each reflected enum is a table of {char* name; char* value; ...} rows
(stride 0x18), found through the pointer to its first item's name. The decl
loader resolves `enumItem[NAME]` keys and enum-valued fields through these
tables. Rows are read while the name keeps the enum's prefix and the values ascend.
Usage: python -I analysis/generate_option_tables.py <Dishonored2.exe> <out.rs>
"""
import json
import struct
import sys

import pefile

exe, out = sys.argv[1], sys.argv[2]
pe = pefile.PE(exe, fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
data = open(exe, 'rb').read()


def section(va):
    for s in pe.sections:
        start = base + s.VirtualAddress
        if start <= va < start + max(s.Misc_VirtualSize, s.SizeOfRawData):
            return s
    return None


def cstr(va):
    s = section(va)
    if s is None:
        return None
    o = s.PointerToRawData + va - base - s.VirtualAddress
    return data[o:data.index(b'\0', o)].decode('latin1')


def va_of(offset):
    for s in pe.sections:
        if s.PointerToRawData <= offset < s.PointerToRawData + s.SizeOfRawData:
            return base + s.VirtualAddress + offset - s.PointerToRawData
    raise ValueError(offset)


# (Rust name, reflected type, first item, item prefix)
ENUMS = [
    ('MENU_ITEMS', 'arkOptionMenuItem_t', 'ARK_OPTION_MENUITEM_CONTROLS', 'ARK_OPTION_MENUITEM_'),
    ('WIDGET_TYPES', 'arkOptionWidgetTypes_t', 'ARK_OPTION_WIDGET_TYPE_STEPPER', 'ARK_OPTION_WIDGET_TYPE_'),
    ('PLATFORMS', 'arkOptionPlatform_t', 'ARK_OPTION_PLATFORM_NONE', 'ARK_OPTION_PLATFORM_'),
    ('AVAILABILITY', 'arkOptionAvailability_t', 'ARK_OPTION_AVAILABILITY_NONE', 'ARK_OPTION_AVAILABILITY_'),
    ('BINDING_TYPES', 'arkOptionBindingTypes_t', 'ARK_OPTION_BINDING_GAME_ACTION', 'ARK_OPTION_BINDING_'),
    ('GAMEPADS', 'arkOptionGamepads_t', 'ARK_OPTION_GAMEPAD_XBOX', 'ARK_OPTION_GAMEPAD_'),
    ('AUDIO_SETTINGS', 'arkSettingAudio_t', 'ARK_AUDIOSETTING_HEADPHONE', 'ARK_AUDIOSETTING_'),
    ('CONTROL_SETTINGS', 'arkSettingControls_t', 'ARK_CONTROLSETTING_CONTROL_SCHEME', 'ARK_CONTROLSETTING_'),
    ('VISUAL_SETTINGS', 'arkSettingVisuals_t', 'ARK_VISUALSETTING_RESOLUTION', 'ARK_VISUALSETTING_'),
    ('GAMEPLAY_SETTINGS', 'arkSettingGameplay_t', 'ARK_GPSETTING_DIFFICULTY', 'ARK_GPSETTING_'),
    ('GAME_ACTIONS', 'eActions_t', 'ACTION_INVALID', 'ACTION_'),
]


def rows(first, prefix):
    va = va_of(data.index(b'\0' + first.encode() + b'\0') + 1)
    p = data.index(struct.pack('<Q', va))
    out = []
    while True:
        name_ptr, value_ptr = struct.unpack('<QQ', data[p:p + 16])
        name, value = cstr(name_ptr), cstr(value_ptr)
        if name is None or not name.startswith(prefix) or value is None:
            return out
        # Values ascend within one enum; a lower value starts the next enum
        # (arkSettingGameplay_t is followed by the master-HUD values).
        if out and int(value, 0) <= out[-1][1]:
            return out
        out.append((name, int(value, 0)))
        p += 0x18


with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('//! Generated by analysis/generate_option_tables.py from Dishonored2.exe.\n')
    f.write('//! Do not edit by hand.\n')
    for rust, kind, first, prefix in ENUMS:
        items = rows(first, prefix)
        f.write('\n/// `%s` (name, value).\n' % kind)
        f.write('pub const %s: &[(&str, i32)] = &[\n' % rust)
        for name, value in items:
            f.write('    (%s, %d),\n' % (json.dumps(name), value))
        f.write('];\n')
        print(rust, len(items))
